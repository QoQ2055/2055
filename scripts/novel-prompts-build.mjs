import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(__dirname, '..', 'public', 'prompts', 'novel');
mkdirSync(outDir, { recursive: true });

function save(name, sys, usr, { temperature = 0.7, max_tokens = 8000 } = {}) {
  const obj = {
    messages: [
      { role: 'system', content: sys.trim() },
      { role: 'user',   content: usr.trim() },
    ],
    temperature,
    max_tokens,
    stream: true,
  };
  const path = resolve(outDir, `${name}.json`);
  writeFileSync(path, JSON.stringify(obj, null, 2), 'utf8');
  console.log(`wrote ${path}  (${JSON.stringify(obj).length} chars)`);
}

