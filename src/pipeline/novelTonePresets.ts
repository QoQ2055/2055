/** 取出当前项目应注入的 preset 段（拼接 tone + audience） */
export function getNovelPresets(tone?: string, audience?: string): string {
  const blocks: string[] = [];
  if (tone && NOVEL_TONE_PRESETS[tone]) blocks.push(NOVEL_TONE_PRESETS[tone]);
  if (audience && NOVEL_AUDIENCE_PRESETS[audience]) blocks.push(NOVEL_AUDIENCE_PRESETS[audience]);
  return blocks.join('\n\n');
}
